/**
 * Automated code generation pipeline (Spec-Driven Development)
 * Single source of truth: specs/
 * Generated targets: packages/core-engine/src/generated/
 */
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { execSync } from 'node:child_process';

const __filename = fileURLToPath(import.meta.url);
const __dirname = path.dirname(__filename);
const rootDir = path.resolve(__dirname, '..');
const specsDir = path.join(rootDir, 'specs');

/**
 * Recursively find files matching an extension within a directory
 */
function findFilesRecursively(dir, extension) {
  let results = [];
  if (!fs.existsSync(dir)) return results;
  const entries = fs.readdirSync(dir, { withFileTypes: true });
  for (const entry of entries) {
    const fullPath = path.join(dir, entry.name);
    if (entry.isDirectory()) {
      results = results.concat(findFilesRecursively(fullPath, extension));
    } else if (entry.isFile() && entry.name.endsWith(extension)) {
      results.push(fullPath);
    }
  }
  return results;
}

async function generate() {
  console.log('🚀 Starting code generation pipeline (Spec-Driven Development)...');

  // 1. Protobuf compilation (dynamic discovery of all .proto files in specs/ -> TypeScript DTOs & Contracts)
  const targetDomainDir = path.join(rootDir, 'packages', 'core-engine', 'src', 'generated', 'domain');
  const protoFiles = findFilesRecursively(specsDir, '.proto');

  if (protoFiles.length > 0) {
    console.log(`📦 [1/2] Protobuf compilation (${protoFiles.length} files found in specs/) -> TypeScript...`);
    fs.mkdirSync(targetDomainDir, { recursive: true });

    const grpcToolsProtoc = path.join(rootDir, 'node_modules', '.bin', 'grpc_tools_node_protoc');
    const tsProtoPlugin = path.join(rootDir, 'node_modules', '.bin', 'protoc-gen-ts_proto');

    // Collect all unique directories containing proto files to pass to --proto_path
    const protoIncludeDirs = [...new Set(protoFiles.map(f => path.dirname(f)))];
    const protoPathArgs = protoIncludeDirs.map(d => `--proto_path="${d}"`).join(' ');

    // ts-proto options: outputServices=generic-definitions creates pure service interfaces
    const cmd = `"${grpcToolsProtoc}" \
      --plugin=protoc-gen-ts_proto="${tsProtoPlugin}" \
      --ts_proto_out="${targetDomainDir}" \
      --ts_proto_opt=outputServices=generic-definitions,outputServices=default,env=node,esModuleInterop=true \
      ${protoPathArgs} \
      ${protoFiles.map(f => `"${f}"`).join(' ')}`;

    execSync(cmd, { stdio: 'inherit' });

    // Automatic generation of typed and exhaustive JSON-RPC Dispatcher
    generateJsonRpcDispatcher(targetDomainDir);
    console.log(`✅ Types and contracts generated in: ${path.relative(rootDir, targetDomainDir)}`);
  }

  // 2. DBML compilation (dynamic discovery of schema.dbml -> SQLite Migration)
  const dbmlFiles = findFilesRecursively(specsDir, '.dbml');
  const targetMigrationsDir = path.join(rootDir, 'packages', 'core-engine', 'src', 'generated', 'migrations');

  if (dbmlFiles.length > 0) {
    const dbmlPath = dbmlFiles[0];
    console.log(`💾 [2/2] DBML compilation (${path.relative(rootDir, dbmlPath)}) -> SQLite Migration...`);
    fs.mkdirSync(targetMigrationsDir, { recursive: true });
    const migrationFile = path.join(targetMigrationsDir, '0001_initial_schema.sql');

    try {
      const rawSql = execSync(`npx dbml2sql --postgres "${dbmlPath}"`, { encoding: 'utf-8' });

      const sqliteSql = rawSql
        .replace(/INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY/g, 'INTEGER PRIMARY KEY AUTOINCREMENT')
        .replace(/COMMENT ON .*?;/g, '')
        .replace(/boolean DEFAULT false/g, 'BOOLEAN DEFAULT 0')
        .replace(/boolean DEFAULT true/g, 'BOOLEAN DEFAULT 1')
        .trim();

      const finalSql = `-- ============================================================================\n-- Code automatically generated from ${path.relative(rootDir, dbmlPath)}\n-- DO NOT EDIT MANUALLY.\n-- ============================================================================\n\nPRAGMA journal_mode = WAL;\nPRAGMA foreign_keys = ON;\n\n${sqliteSql}\n\nINSERT OR IGNORE INTO project_metadata (key, value) VALUES ('schema_version', '1');\n`;

      fs.writeFileSync(migrationFile, finalSql, 'utf-8');
      console.log(`✅ SQL migration generated in: ${path.relative(rootDir, migrationFile)}`);
    } catch (err) {
      console.error('❌ Error during SQL generation from DBML:', err.message);
    }
  }

  console.log('🎉 Code generation pipeline completed successfully!');
}

/**
 * Automatically generates the strict JSON-RPC dispatcher
 * This file guarantees that a developer or agent MUST implement all TerrainEngineService methods
 */
function generateJsonRpcDispatcher(targetDir) {
  const dispatcherFile = path.join(targetDir, 'jsonRpcDispatcher.ts');
  const content = `/* eslint-disable */
/**
 * Code automatically generated by scripts/codegen.js from service contracts
 * DO NOT EDIT MANUALLY.
 */

import {
  TerrainEngineServiceDefinition,
  PaintAreaCommand,
  PlacePresetCommand,
  MovePresetCommand,
  DeletePresetCommand,
  UndoCommand,
  RedoCommand,
  RenderBBoxImageRequest
} from './services.js';

export interface ITerrainEngineHandler {
  paintArea(command: PaintAreaCommand): Promise<unknown>;
  placePreset(command: PlacePresetCommand): Promise<unknown>;
  movePreset(command: MovePresetCommand): Promise<unknown>;
  deletePreset(command: DeletePresetCommand): Promise<unknown>;
  undo(command: UndoCommand): Promise<unknown>;
  redo(command: RedoCommand): Promise<unknown>;
  renderBBoxImage(request: RenderBBoxImageRequest): Promise<unknown>;
}

export interface JsonRpcRequest {
  jsonrpc: '2.0';
  id?: string | number | null;
  method: string;
  params?: any;
}

export interface JsonRpcResponse {
  jsonrpc: '2.0';
  id?: string | number | null;
  result?: any;
  error?: {
    code: number;
    message: string;
    data?: any;
  };
}

/**
 * JSON-RPC Router ensuring exhaustive dispatching of service methods
 */
export async function dispatchJsonRpc(
  handler: ITerrainEngineHandler,
  request: JsonRpcRequest
): Promise<JsonRpcResponse> {
  const { id, method, params } = request;

  try {
    switch (method) {
      case 'paintArea':
        return { jsonrpc: '2.0', id, result: await handler.paintArea(PaintAreaCommand.fromJSON(params || {})) };
      case 'placePreset':
        return { jsonrpc: '2.0', id, result: await handler.placePreset(PlacePresetCommand.fromJSON(params || {})) };
      case 'movePreset':
        return { jsonrpc: '2.0', id, result: await handler.movePreset(MovePresetCommand.fromJSON(params || {})) };
      case 'deletePreset':
        return { jsonrpc: '2.0', id, result: await handler.deletePreset(DeletePresetCommand.fromJSON(params || {})) };
      case 'undo':
        return { jsonrpc: '2.0', id, result: await handler.undo(UndoCommand.fromJSON(params || {})) };
      case 'redo':
        return { jsonrpc: '2.0', id, result: await handler.redo(RedoCommand.fromJSON(params || {})) };
      case 'renderBBoxImage':
        return { jsonrpc: '2.0', id, result: await handler.renderBBoxImage(RenderBBoxImageRequest.fromJSON(params || {})) };
      default:
        return {
          jsonrpc: '2.0',
          id,
          error: { code: -32601, message: \`Unknown method: \${method}\` }
        };
    }
  } catch (error: any) {
    return {
      jsonrpc: '2.0',
      id,
      error: { code: -32000, message: error?.message || 'Internal engine error' }
    };
  }
}
`;

  fs.writeFileSync(dispatcherFile, content, 'utf-8');
}

generate().catch(err => {
  console.error('❌ Generation failed:', err);
  process.exit(1);
});

