import { exporter } from '@dbml/core';

/**
 * Normalizes PostgreSQL SQL output from @dbml/core into standard SQLite dialect
 *
 * @param {string} rawSql - PostgreSQL DDL from exporter
 * @param {object} [options]
 * @param {string} [options.metadataTable] - Optional table name to record schema_version
 * @param {string} [options.schemaVersion='1'] - Version value to record
 * @param {string} [options.sourcePath='schema.dbml'] - Source file path for comment header
 * @returns {string} Normalized SQLite DDL
 */
export function normalizePostgresSqlToSqlite(rawSql, options = {}) {
  const sourcePath = options.sourcePath || 'schema.dbml';
  const metadataTable = options.metadataTable;
  const schemaVersion = options.schemaVersion || '1';

  const sqliteSql = rawSql
    .replace(/INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY/g, 'INTEGER PRIMARY KEY AUTOINCREMENT')
    .replace(/COMMENT ON .*?;/g, '')
    .replace(/boolean DEFAULT false/g, 'BOOLEAN DEFAULT 0')
    .replace(/boolean DEFAULT true/g, 'BOOLEAN DEFAULT 1')
    .trim();

  let header = `-- ============================================================================\n` +
    `-- Code automatically generated from ${sourcePath}\n` +
    `-- DO NOT EDIT MANUALLY.\n` +
    `-- ============================================================================\n\n` +
    `PRAGMA journal_mode = WAL;\nPRAGMA foreign_keys = ON;\n\n` +
    sqliteSql + '\n';

  if (metadataTable) {
    header += `\nINSERT OR IGNORE INTO ${metadataTable} (key, value) VALUES ('schema_version', '${schemaVersion}');\n`;
  }

  return header;
}

/**
 * Compiles DBML text directly into a SQLite migration script
 *
 * @param {string} dbmlContent - DBML markup string
 * @param {object} [options] - Options passed to normalizer
 * @returns {string} Ready-to-execute SQLite migration script
 */
export function compileDbmlToSqlite(dbmlContent, options = {}) {
  const rawPostgresSql = exporter.export(dbmlContent, 'postgres');
  return normalizePostgresSqlToSqlite(rawPostgresSql, options);
}
