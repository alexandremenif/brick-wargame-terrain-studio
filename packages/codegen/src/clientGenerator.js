/**
 * Synthesizes a strongly-typed JSON-RPC 2.0 client for a protobuf service
 *
 * @param {object} service - Service definition from protoParser
 * @param {object} [options]
 * @param {string} [options.apiPackage='@lego-wargame-terrain-studio/api']
 * @returns {string} TypeScript code for the client
 */
export function generateClientForService(service, options = {}) {
  const apiPackage = options.apiPackage || '@lego-wargame-terrain-studio/api';

  const clientClassName = `${service.name}Client`;
  const serviceInterfaceName = service.name;

  const requestTypes = [...new Set(service.methods.map(m => m.requestType))];
  const responseTypes = [...new Set(service.methods.map(m => m.responseType))];
  const allImportTypes = [...new Set([serviceInterfaceName, ...requestTypes, ...responseTypes])];

  const clientMethods = service.methods
    .map(
      m => `  async ${m.camelCaseName}(command: ${m.requestType}): Promise<${m.responseType}> {
    return this.transport.call<${m.responseType}>('${m.camelCaseName}', command);
  }`
    )
    .join('\n\n');

  return `/* eslint-disable */
/**
 * Code automatically generated by @lego-wargame-terrain-studio/codegen from service contracts
 * DO NOT EDIT MANUALLY.
 */

import type {
  ${allImportTypes.join(',\n  ')}
} from '${apiPackage}';

export interface JsonRpcTransport {
  call<TResult>(method: string, params: unknown): Promise<TResult>;
}

export class ${clientClassName} implements ${serviceInterfaceName} {
  constructor(private transport: JsonRpcTransport) {}

${clientMethods}
}
`;
}
