import fs from 'node:fs';
import path from 'node:path';
import { execSync } from 'node:child_process';
import { parseProtoContent } from './protoParser.js';
import { generateDispatcherForService } from './dispatcherGenerator.js';
import { generateClientForService } from './clientGenerator.js';
import { compileDbmlToSqlite } from './dbmlCompiler.js';

import { fileURLToPath } from 'node:url';

/**
 * Generates pure TypeScript service interface with camelCase methods
 */
export function generateInterfaceForService(service, options = {}) {
  const requestTypes = [...new Set(service.methods.map(m => m.requestType))];
  const responseTypes = [...new Set(service.methods.map(m => m.responseType))];
  const allImportTypes = [...new Set([...requestTypes, ...responseTypes])];

  const methods = service.methods
    .map(m => `  ${m.camelCaseName}(command: ${m.requestType}): Promise<${m.responseType}>;`)
    .join('\n');

  return `/* eslint-disable */
/**
 * Public service interface definition
 * Auto-generated by @lego-wargame-terrain-studio/codegen
 */

import type {
  ${allImportTypes.join(',\n  ')}
} from '${options.importFrom || './api.js'}';

export interface ${service.name} {
${methods}
}
`;
}

/**
 * Recursively find files matching an extension within a directory
 */
export function findFilesRecursively(dir, extension, fsModule = fs) {
  let results = [];
  if (!fsModule.existsSync(dir)) return results;
  const entries = fsModule.readdirSync(dir, { withFileTypes: true });
  for (const entry of entries) {
    const fullPath = path.join(dir, entry.name);
    if (entry.isDirectory()) {
      results = results.concat(findFilesRecursively(fullPath, extension, fsModule));
    } else if (entry.isFile() && entry.name.endsWith(extension)) {
      results.push(fullPath);
    }
  }
  return results;
}

/**
 * Locates an executable binary across node_modules/.bin directories, searching upwards
 */
export function resolveBinary(name, searchDirs = []) {
  const dirsToSearch = [
    ...searchDirs,
    process.cwd(),
    path.dirname(fileURLToPath(import.meta.url))
  ];

  for (const dir of dirsToSearch) {
    if (!dir) continue;
    let curr = path.resolve(dir);
    while (true) {
      const binPath = path.join(curr, 'node_modules', '.bin', name);
      if (fs.existsSync(binPath)) {
        return binPath;
      }
      const parent = path.dirname(curr);
      if (parent === curr) break;
      curr = parent;
    }
  }

  return name;
}

/**
 * Executes the full code generation pipeline
 */
export async function runCodegen(options) {
  const {
    specsDir,
    targetApiDir,
    targetClientDir,
    targetServerDir,
    targetServerPersistenceDir,
    targetMigrationsDir,
    rootDir = process.cwd(),
    metadataTable,
    schemaVersion = '1',
    exec = execSync,
    logger = console
  } = options;

  logger.log('🚀 Starting code generation pipeline (Spec-Driven Development)...');

  // ==========================================================================
  // 1. Protobuf compilation -> TypeScript Contracts, Client, & Dispatcher
  // ==========================================================================
  const allProtoFiles = findFilesRecursively(specsDir, '.proto');

  // Distinguish public API contracts (domain.proto, api.proto) from internal server ports (persistence.proto)
  const publicProtoFiles = allProtoFiles.filter(f => {
    const base = path.basename(f);
    return base === 'domain.proto' || base === 'api.proto';
  });

  const internalProtoFiles = allProtoFiles.filter(f => {
    const base = path.basename(f);
    return base !== 'domain.proto' && base !== 'api.proto';
  });

  const searchDirs = [rootDir, path.resolve(rootDir, '..'), process.cwd()];
  const grpcToolsProtoc = resolveBinary('grpc_tools_node_protoc', searchDirs);
  const tsProtoPlugin = resolveBinary('protoc-gen-ts_proto', searchDirs);
  const protoIncludeDirs = [...new Set(allProtoFiles.map(f => path.dirname(f)))];
  const protoPathArgs = protoIncludeDirs.map(d => `--proto_path="${d}"`).join(' ');

  // A. Compile public contracts into packages/api
  if (publicProtoFiles.length > 0 && targetApiDir) {
    logger.log(`📦 [1/3] Compiling public API contracts into ${targetApiDir}...`);
    fs.mkdirSync(targetApiDir, { recursive: true });

    const apiCmd = `"${grpcToolsProtoc}" \
      --plugin=protoc-gen-ts_proto="${tsProtoPlugin}" \
      --ts_proto_out="${targetApiDir}" \
      --ts_proto_opt=outputServices=none,outputEncodeMethods=false,outputJsonMethods=false,outputPartialMethods=false,exportCommonSymbols=false,env=node,esModuleInterop=true,importSuffix=.js \
      ${protoPathArgs} \
      ${publicProtoFiles.map(f => `"${f}"`).join(' ')}`;

    exec(apiCmd, { stdio: 'inherit' });

    // Ensure packages/api/src/index.ts re-exports the generated contracts
    const apiIndexFile = path.join(path.dirname(targetApiDir), 'index.ts');
    const apiIndexContent = `/**
 * Public domain types and API contracts
 * Auto-generated by @lego-wargame-terrain-studio/codegen
 */
export * from './generated/domain.js';
export * from './generated/api.js';
export * from './generated/service.js';
`;
    fs.writeFileSync(apiIndexFile, apiIndexContent, 'utf-8');

    // Generate service interface in packages/api, client in packages/client, dispatcher in packages/server
    for (const protoFile of publicProtoFiles) {
      const content = fs.readFileSync(protoFile, 'utf-8');
      const { services } = parseProtoContent(content, path.basename(protoFile));

      for (const service of services) {
        logger.log(`⚡ Generating service interface for: ${service.name} in api...`);
        const interfaceCode = generateInterfaceForService(service, { importFrom: './api.js' });
        fs.writeFileSync(path.join(targetApiDir, 'service.ts'), interfaceCode, 'utf-8');

        if (targetClientDir) {
          logger.log(`⚡ Generating JSON-RPC client for service: ${service.name} in client...`);
          fs.mkdirSync(targetClientDir, { recursive: true });
          const clientCode = generateClientForService(service, {
            apiPackage: '@lego-wargame-terrain-studio/api'
          });
          fs.writeFileSync(path.join(targetClientDir, 'client.ts'), clientCode, 'utf-8');
        }

        if (targetServerDir) {
          logger.log(`⚡ Generating JSON-RPC dispatcher for service: ${service.name} in server...`);
          fs.mkdirSync(targetServerDir, { recursive: true });
          const dispatcherCode = generateDispatcherForService(service, {
            importFrom: '@lego-wargame-terrain-studio/api'
          });
          fs.writeFileSync(path.join(targetServerDir, 'dispatcher.ts'), dispatcherCode, 'utf-8');
        }
      }
    }
  }

  // B. Compile internal server protos (persistence.proto) into packages/server/src/persistence/generated
  if (internalProtoFiles.length > 0 && targetServerPersistenceDir) {
    logger.log(`📦 [2/3] Compiling internal server contracts into ${targetServerPersistenceDir}...`);
    fs.mkdirSync(targetServerPersistenceDir, { recursive: true });

    const serverCmd = `"${grpcToolsProtoc}" \
      --plugin=protoc-gen-ts_proto="${tsProtoPlugin}" \
      --ts_proto_out="${targetServerPersistenceDir}" \
      --ts_proto_opt=outputServices=none,outputEncodeMethods=false,outputJsonMethods=false,outputPartialMethods=false,exportCommonSymbols=false,env=node,esModuleInterop=true,importSuffix=.js \
      ${protoPathArgs} \
      ${internalProtoFiles.map(f => `"${f}"`).join(' ')}`;

    exec(serverCmd, { stdio: 'inherit' });
  }

  // ==========================================================================
  // 2. DBML compilation -> SQLite Migration
  // ==========================================================================
  const dbmlFiles = findFilesRecursively(specsDir, '.dbml');

  if (dbmlFiles.length > 0 && targetMigrationsDir) {
    const dbmlPath = dbmlFiles[0];
    logger.log(`💾 [3/3] DBML compilation (${path.relative(rootDir, dbmlPath)}) -> SQLite Migration...`);
    fs.mkdirSync(targetMigrationsDir, { recursive: true });
    const migrationFile = path.join(targetMigrationsDir, '0001_initial_schema.sql');

    try {
      const dbmlContent = fs.readFileSync(dbmlPath, 'utf-8');
      const sqliteSql = compileDbmlToSqlite(dbmlContent, {
        metadataTable,
        schemaVersion,
        sourcePath: path.relative(rootDir, dbmlPath)
      });

      fs.writeFileSync(migrationFile, sqliteSql, 'utf-8');
      logger.log(`✅ SQL migration generated in: ${migrationFile}`);
    } catch (err) {
      logger.error('❌ Error during SQL generation from DBML:', err.message);
      throw err;
    }
  }

  logger.log('🎉 Code generation pipeline completed successfully!');
}
