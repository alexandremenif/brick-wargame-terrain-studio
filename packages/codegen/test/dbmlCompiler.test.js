import { test, describe } from 'node:test';
import assert from 'node:assert/strict';
import { compileDbmlToSqlite, normalizePostgresSqlToSqlite } from '../src/dbmlCompiler.js';

describe('dbmlCompiler', () => {
  const genericDbml = `
Table customers {
  id integer [pk]
  name varchar [not null]
  is_active boolean [default: true]
  Note: 'Customer master data'
}

Table orders {
  id integer [pk]
  customer_id integer [not null]
  total_amount real [not null]
  is_cancelled boolean [default: false]
}
`;

  test('compiles DBML to SQLite with autoincrement and boolean normalizations', () => {
    const sqliteSql = compileDbmlToSqlite(genericDbml, { sourcePath: 'test_schema.dbml' });

    // Verifies SQLite PRAGMAs
    assert.ok(sqliteSql.includes('PRAGMA journal_mode = WAL;'));
    assert.ok(sqliteSql.includes('PRAGMA foreign_keys = ON;'));

    // Verifies table definitions exist
    assert.ok(sqliteSql.includes('CREATE TABLE "customers"'));
    assert.ok(sqliteSql.includes('CREATE TABLE "orders"'));

    // Verifies Postgres comments are removed
    assert.ok(!sqliteSql.includes('COMMENT ON'));

    // Verifies header references the source path
    assert.ok(sqliteSql.includes('-- Code automatically generated from test_schema.dbml'));
  });

  test('converts PostgreSQL IDENTITY to SQLite AUTOINCREMENT', () => {
    const rawPostgresSql = `
CREATE TABLE "items" (
  "id" INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  "label" varchar NOT NULL
);
`;

    const normalized = normalizePostgresSqlToSqlite(rawPostgresSql);
    assert.ok(normalized.includes('"id" INTEGER PRIMARY KEY AUTOINCREMENT'));
    assert.ok(!normalized.includes('GENERATED BY DEFAULT AS IDENTITY'));
  });

  test('normalizes boolean defaults from false/true to 0/1', () => {
    const rawPostgresSql = `
CREATE TABLE "flags" (
  "flag_a" boolean DEFAULT false,
  "flag_b" boolean DEFAULT true
);
`;

    const normalized = normalizePostgresSqlToSqlite(rawPostgresSql);
    assert.ok(normalized.includes('"flag_a" BOOLEAN DEFAULT 0'));
    assert.ok(normalized.includes('"flag_b" BOOLEAN DEFAULT 1'));
  });

  test('appends metadata table version when metadataTable option is supplied', () => {
    const rawPostgresSql = 'CREATE TABLE "dummy" ("id" int);';
    const normalized = normalizePostgresSqlToSqlite(rawPostgresSql, {
      metadataTable: 'system_metadata',
      schemaVersion: '42'
    });

    assert.ok(
      normalized.includes("INSERT OR IGNORE INTO system_metadata (key, value) VALUES ('schema_version', '42');")
    );
  });

  test('does not append metadata table version when metadataTable is omitted', () => {
    const rawPostgresSql = 'CREATE TABLE "dummy" ("id" int);';
    const normalized = normalizePostgresSqlToSqlite(rawPostgresSql);

    assert.ok(!normalized.includes('INSERT OR IGNORE INTO'));
  });
});
