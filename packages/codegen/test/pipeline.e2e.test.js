import { test, describe } from 'node:test';
import assert from 'node:assert/strict';
import fs from 'node:fs';
import os from 'node:os';
import path from 'node:path';
import { runCodegen } from '../src/pipeline.js';

describe('pipeline e2e (isolated in os.tmpdir())', () => {
  test('executes end-to-end code generation on generic test schemas in /tmp', async () => {
    const tempDir = fs.mkdtempSync(path.join(os.tmpdir(), 'codegen-sandbox-'));

    try {
      const specsDir = path.join(tempDir, 'specs');
      const domainSpecsDir = path.join(specsDir, 'domain');
      const persistenceSpecsDir = path.join(specsDir, 'persistence');
      const targetDomainDir = path.join(tempDir, 'output', 'domain');
      const targetMigrationsDir = path.join(tempDir, 'output', 'migrations');

      fs.mkdirSync(domainSpecsDir, { recursive: true });
      fs.mkdirSync(persistenceSpecsDir, { recursive: true });

      // Generic test protobuf fixture
      const protoContent = `syntax = "proto3";
package generic.test;

message ComputeRequest {
  int32 x = 1;
  int32 y = 2;
}

message ComputeResponse {
  int32 value = 1;
}

// @jsonrpc
service ComputeService {
  rpc Compute (ComputeRequest) returns (ComputeResponse);
}
`;
      fs.writeFileSync(path.join(domainSpecsDir, 'compute.proto'), protoContent, 'utf-8');

      // Generic test DBML fixture
      const dbmlContent = `Table inventory {
  id integer [pk]
  sku varchar [not null]
  quantity integer [default: 0]
}
`;
      fs.writeFileSync(path.join(persistenceSpecsDir, 'inventory.dbml'), dbmlContent, 'utf-8');

      const silentLogger = { log: () => {}, error: () => {}, warn: () => {} };

      // Run pipeline with real tools
      await runCodegen({
        rootDir: process.cwd(),
        specsDir,
        targetDomainDir,
        targetMigrationsDir,
        logger: silentLogger
      });

      // 1. Verify TypeScript DTO was compiled by protoc
      const generatedProtoTs = path.join(targetDomainDir, 'compute.ts');
      assert.ok(fs.existsSync(generatedProtoTs), 'compute.ts should be generated by protoc');
      const protoTsContent = fs.readFileSync(generatedProtoTs, 'utf-8');
      assert.ok(protoTsContent.includes('ComputeServiceDefinition'));

      // 2. Verify JSON-RPC Dispatcher was synthesized for the @jsonrpc service
      const generatedDispatcherTs = path.join(targetDomainDir, 'jsonRpcDispatcher.ts');
      assert.ok(fs.existsSync(generatedDispatcherTs), 'jsonRpcDispatcher.ts should be generated');
      const dispatcherContent = fs.readFileSync(generatedDispatcherTs, 'utf-8');
      assert.ok(dispatcherContent.includes('export interface IComputeHandler {'));
      assert.ok(dispatcherContent.includes('compute(command: ComputeRequest): Promise<unknown>;'));
      assert.ok(dispatcherContent.includes("case 'compute':"));

      // 3. Verify SQLite migration was compiled from DBML
      const generatedMigrationSql = path.join(targetMigrationsDir, '0001_initial_schema.sql');
      assert.ok(fs.existsSync(generatedMigrationSql), '0001_initial_schema.sql should be generated');
      const migrationContent = fs.readFileSync(generatedMigrationSql, 'utf-8');
      assert.ok(migrationContent.includes('CREATE TABLE "inventory"'));
      assert.ok(migrationContent.includes('PRAGMA journal_mode = WAL;'));
    } finally {
      // Ensure isolated test directory is cleaned up
      fs.rmSync(tempDir, { recursive: true, force: true });
    }
  });

  test('completes smoothly when specs directory contains no proto or dbml files', async () => {
    const tempDir = fs.mkdtempSync(path.join(os.tmpdir(), 'codegen-empty-sandbox-'));

    try {
      const specsDir = path.join(tempDir, 'empty_specs');
      const targetDomainDir = path.join(tempDir, 'output', 'domain');
      const targetMigrationsDir = path.join(tempDir, 'output', 'migrations');
      fs.mkdirSync(specsDir, { recursive: true });

      const silentLogger = { log: () => {}, error: () => {}, warn: () => {} };

      await runCodegen({
        rootDir: process.cwd(),
        specsDir,
        targetDomainDir,
        targetMigrationsDir,
        logger: silentLogger
      });

      assert.ok(!fs.existsSync(targetDomainDir));
      assert.ok(!fs.existsSync(targetMigrationsDir));
    } finally {
      fs.rmSync(tempDir, { recursive: true, force: true });
    }
  });
});
