import { test, describe } from 'node:test';
import assert from 'node:assert/strict';
import Database from 'better-sqlite3';
import {
  inlineColumnDirectives,
  stripPostgresComments,
  normalizeAutoIncrement,
  normalizeBooleans,
  inlineForeignKeys,
  formatSqliteScript,
  normalizePostgresSqlToSqlite
} from '../src/sqlNormalizer.js';

describe('sqlNormalizer (Unit Tests)', () => {
  describe('inlineColumnDirectives', () => {
    test('inlines generated: and check: column notes into CREATE TABLE column definitions', () => {
      const input = `
CREATE TABLE "assets" (
  "id" varchar(36) PRIMARY KEY NOT NULL,
  "name" varchar(100) NOT NULL,
  "data" blob NOT NULL
);

COMMENT ON COLUMN "assets"."id" IS 'check: id = (data ->> ''$.id'')';
COMMENT ON COLUMN "assets"."name" IS 'generated: (data ->> ''$.name'')';
COMMENT ON COLUMN "assets"."data" IS 'check: json_valid(data, 4)';
`;
      const output = inlineColumnDirectives(input);
      assert.ok(output.includes(`"id" varchar(36) PRIMARY KEY NOT NULL CHECK (id = (data ->> '$.id')),`));
      assert.ok(output.includes(`"name" varchar(100) GENERATED ALWAYS AS ((data ->> '$.name')) STORED NOT NULL,`));
      assert.ok(output.includes(`"data" blob NOT NULL CHECK (json_valid(data, 4))`));
    });
  });

  describe('stripPostgresComments', () => {
    test('removes COMMENT ON statements without altering table DDL', () => {
      const input = `
CREATE TABLE "items" ("id" int);
COMMENT ON TABLE "items" IS 'Item master';
COMMENT ON COLUMN "items"."id" IS 'Identifier';
`;
      const output = stripPostgresComments(input);
      assert.strictEqual(output.includes('COMMENT ON'), false);
      assert.ok(output.includes('CREATE TABLE "items" ("id" int);'));
    });
  });

  describe('normalizeAutoIncrement', () => {
    test('converts PostgreSQL IDENTITY to SQLite AUTOINCREMENT', () => {
      const input = `CREATE TABLE "events" ("id" INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, "title" text);`;
      const output = normalizeAutoIncrement(input);

      assert.ok(output.includes('"id" INTEGER PRIMARY KEY AUTOINCREMENT'));
      assert.strictEqual(output.includes('GENERATED BY DEFAULT AS IDENTITY'), false);
    });

    test('preserves regular non-identity primary keys intact', () => {
      const input = `CREATE TABLE "events" ("id" INTEGER PRIMARY KEY, "uuid" varchar PRIMARY KEY);`;
      const output = normalizeAutoIncrement(input);

      assert.strictEqual(output, input);
    });
  });

  describe('normalizeBooleans', () => {
    test('converts boolean DEFAULT false/true to numeric 0/1', () => {
      const input = `
"active" boolean DEFAULT true,
"archived" boolean DEFAULT false
`;
      const output = normalizeBooleans(input);

      assert.ok(output.includes('"active" BOOLEAN DEFAULT 1'));
      assert.ok(output.includes('"archived" BOOLEAN DEFAULT 0'));
    });

    test('preserves NOT NULL constraint when converting boolean defaults', () => {
      const input = `
"is_verified" boolean NOT NULL DEFAULT true,
"is_deleted" boolean NOT NULL DEFAULT false
`;
      const output = normalizeBooleans(input);

      assert.ok(output.includes('"is_verified" BOOLEAN NOT NULL DEFAULT 1'));
      assert.ok(output.includes('"is_deleted" BOOLEAN NOT NULL DEFAULT 0'));
    });
  });

  describe('inlineForeignKeys', () => {
    test('inlines foreign key constraint into the referencing CREATE TABLE block and removes ALTER TABLE', () => {
      const input = `
CREATE TABLE "authors" (
  "id" integer PRIMARY KEY
);

CREATE TABLE "books" (
  "id" integer PRIMARY KEY,
  "author_id" integer NOT NULL
);

ALTER TABLE "books" ADD FOREIGN KEY ("author_id") REFERENCES "authors" ("id") ON DELETE CASCADE;
`;
      const output = inlineForeignKeys(input);

      assert.strictEqual(output.includes('ALTER TABLE'), false);
      assert.ok(
        output.includes('FOREIGN KEY ("author_id") REFERENCES "authors" ("id") ON DELETE CASCADE'),
        'Foreign key clause must be inlined into books table'
      );
    });

    test('handles multiple foreign keys and different ON DELETE / ON UPDATE actions', () => {
      const input = `
CREATE TABLE "rel" (
  "id" integer PRIMARY KEY,
  "a_id" integer,
  "b_id" integer
);

ALTER TABLE "rel" ADD FOREIGN KEY ("a_id") REFERENCES "a" ("id") ON DELETE SET NULL;
ALTER TABLE "rel" ADD FOREIGN KEY ("b_id") REFERENCES "b" ("id") ON DELETE RESTRICT ON UPDATE CASCADE;
`;
      const output = inlineForeignKeys(input);

      assert.strictEqual(output.includes('ALTER TABLE'), false);
      assert.ok(output.includes('FOREIGN KEY ("a_id") REFERENCES "a" ("id") ON DELETE SET NULL'));
      assert.ok(output.includes('FOREIGN KEY ("b_id") REFERENCES "b" ("id") ON DELETE RESTRICT ON UPDATE CASCADE'));
    });
  });

  describe('formatSqliteScript', () => {
    test('prepends PRAGMAs, header comments, and appends schema_version when metadataTable is given', () => {
      const body = 'CREATE TABLE "t" ("id" int);';
      const output = formatSqliteScript(body, {
        sourcePath: 'specs/test.dbml',
        metadataTable: 'sys_metadata',
        schemaVersion: '3'
      });

      assert.ok(output.includes('-- Code automatically generated from specs/test.dbml'));
      assert.ok(output.includes('PRAGMA journal_mode = WAL;'));
      assert.ok(output.includes('PRAGMA foreign_keys = ON;'));
      assert.ok(output.includes("INSERT OR IGNORE INTO sys_metadata (key, value) VALUES ('schema_version', '3');"));
    });

    test('omits metadata insert when metadataTable option is omitted', () => {
      const body = 'CREATE TABLE "t" ("id" int);';
      const output = formatSqliteScript(body);

      assert.strictEqual(output.includes('INSERT OR IGNORE INTO'), false);
    });
  });

  describe('normalizePostgresSqlToSqlite (Full Pipeline)', () => {
    test('produces valid SQLite DDL that executes cleanly in better-sqlite3 with foreign key, check, and generated column enforcement', () => {
      const rawPostgres = `
CREATE TABLE "categories" (
  "id" INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  "name" varchar NOT NULL
);

CREATE TABLE "products" (
  "id" INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  "category_id" integer NOT NULL,
  "is_featured" boolean NOT NULL DEFAULT false,
  "sku" varchar NOT NULL,
  "data" blob NOT NULL
);

COMMENT ON TABLE "products" IS 'Catalog products';
COMMENT ON COLUMN "products"."sku" IS 'generated: (data ->> ''$.sku'')';
COMMENT ON COLUMN "products"."data" IS 'check: json_valid(data, 4)';
ALTER TABLE "products" ADD FOREIGN KEY ("category_id") REFERENCES "categories" ("id") ON DELETE CASCADE;
`;

      const sqliteDdl = normalizePostgresSqlToSqlite(rawPostgres, {
        sourcePath: 'catalog.dbml',
        metadataTable: 'meta',
        schemaVersion: '1'
      });

      // Prepare in-memory SQLite database
      const db = new Database(':memory:');
      db.exec('CREATE TABLE "meta" ("key" varchar PRIMARY KEY, "value" text);');

      assert.doesNotThrow(() => {
        db.exec(sqliteDdl);
      }, 'Full normalized DDL must execute cleanly in SQLite');

      // Verify FK enforcement
      assert.throws(
        () => {
          db.prepare('INSERT INTO products (category_id, data) VALUES (?, jsonb(?))').run(999, '{"sku":"SKU-999"}');
        },
        /FOREIGN KEY constraint failed/,
        'FK must be enforced'
      );

      // Verify insert with boolean default and generated column extraction from JSONB
      db.prepare('INSERT INTO categories (name) VALUES (?)').run('Electronics');
      db.prepare('INSERT INTO products (category_id, data) VALUES (?, jsonb(?))').run(1, '{"sku":"SKU-001"}');

      const product = db.prepare('SELECT id, is_featured, sku FROM products WHERE id = 1').get();
      assert.strictEqual(product.is_featured, 0, 'Default boolean must be 0 in SQLite');
      assert.strictEqual(product.sku, 'SKU-001', 'STORED generated column must extract $.sku from JSONB data');

      // Verify CHECK constraint enforcement on non-JSONB data
      assert.throws(
        () => {
          db.prepare('INSERT INTO products (category_id, data) VALUES (?, ?)').run(1, '{"sku":"PLAIN-JSON"}');
        },
        /CHECK constraint failed/,
        'CHECK constraint from COMMENT ON COLUMN must reject plain text JSON'
      );

      // Verify cascade
      db.prepare('DELETE FROM categories WHERE id = 1').run();
      const count = db.prepare('SELECT COUNT(*) as c FROM products').get();
      assert.strictEqual(count.c, 0, 'Cascade delete must clear products');

      db.close();
    });
  });
});
