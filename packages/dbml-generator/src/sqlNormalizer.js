/**
 * Modular SQL Normalizer: Converts PostgreSQL SQL DDL output from @dbml/core into standard SQLite dialect.
 */

/**
 * 1. Inlines column-level `generated:` and `check:` directives declared in DBML column notes
 * (exported by @dbml/core as PostgreSQL COMMENT ON COLUMN statements) into their CREATE TABLE definitions.
 *
 * @param {string} sql
 * @returns {string}
 */
export function inlineColumnDirectives(sql) {
  const commentRegex = /COMMENT ON COLUMN\s+["']?(\w+)["']?\.["']?(\w+)["']?\s+IS\s+'((?:[^']|'')*)';/gi;

  const directives = [];
  let match;
  while ((match = commentRegex.exec(sql)) !== null) {
    const [, table, column, rawNote] = match;
    const note = rawNote.replace(/''/g, "'").trim();
    if (note.startsWith('generated:')) {
      const expr = note.slice('generated:'.length).trim();
      directives.push({ table, column, kind: 'generated', expr });
    } else if (note.startsWith('check:')) {
      const expr = note.slice('check:'.length).trim();
      directives.push({ table, column, kind: 'check', expr });
    }
  }

  let resultSql = sql;
  for (const { table, column, kind, expr } of directives) {
    const tableRegex = new RegExp(`(CREATE TABLE ["']?${table}["']?\\s*\\()([\\s\\S]*?)(\\n\\);)`, 'i');
    resultSql = resultSql.replace(tableRegex, (_fullMatch, open, body, close) => {
      const colRegex = new RegExp(`(^\\s*["']?${column}["']?\\s+[^,\\n]+?)(,?)$`, 'im');
      const updatedBody = body.replace(colRegex, (_colMatch, colDef, trailingComma) => {
        if (kind === 'generated') {
          if (/\bNOT\s+NULL\b/i.test(colDef)) {
            return colDef.replace(/\bNOT\s+NULL\b/i, `GENERATED ALWAYS AS (${expr}) STORED NOT NULL`) + trailingComma;
          }
          return `${colDef} GENERATED ALWAYS AS (${expr}) STORED${trailingComma}`;
        }
        return `${colDef} CHECK (${expr})${trailingComma}`;
      });
      return `${open}${updatedBody}${close}`;
    });
  }

  return resultSql;
}

/**
 * 2. Removes PostgreSQL COMMENT ON statements unsupported in SQLite.
 *
 * @param {string} sql
 * @returns {string}
 */
export function stripPostgresComments(sql) {
  return sql.replace(/COMMENT ON .*?;/g, '');
}

/**
 * 2. Converts PostgreSQL IDENTITY primary keys into SQLite AUTOINCREMENT.
 *
 * @param {string} sql
 * @returns {string}
 */
export function normalizeAutoIncrement(sql) {
  return sql.replace(
    /INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY/g,
    'INTEGER PRIMARY KEY AUTOINCREMENT'
  );
}

/**
 * 3. Normalizes boolean default values to SQLite integers (0 and 1),
 * while preserving optional constraints such as NOT NULL.
 *
 * @param {string} sql
 * @returns {string}
 */
export function normalizeBooleans(sql) {
  return sql
    .replace(/\bboolean\b(\s+NOT\s+NULL)?\s+DEFAULT\s+false\b/gi, 'BOOLEAN$1 DEFAULT 0')
    .replace(/\bboolean\b(\s+NOT\s+NULL)?\s+DEFAULT\s+true\b/gi, 'BOOLEAN$1 DEFAULT 1');
}

/**
 * 4. Extracts foreign keys from PostgreSQL ALTER TABLE statements and inlines them
 * into their respective CREATE TABLE definitions (as required by SQLite).
 *
 * @param {string} sql
 * @returns {string}
 */
export function inlineForeignKeys(sql) {
  const alterFkRegex = /ALTER TABLE\s+["']?(\w+)["']?\s+ADD(?:\s+CONSTRAINT\s+["']?\w+["']?)?\s+FOREIGN KEY\s*\(([^)]+)\)\s*REFERENCES\s+["']?(\w+)["']?\s*\(([^)]+)\)(?:\s+ON DELETE\s+([A-Z ]+?))?(?:\s+ON UPDATE\s+([A-Z ]+?))?\s*;/gi;

  const fksByTable = new Map();
  let match;
  while ((match = alterFkRegex.exec(sql)) !== null) {
    const [, table, cols, targetTable, targetCols, onDelete, onUpdate] = match;
    if (!fksByTable.has(table)) {
      fksByTable.set(table, []);
    }
    let fkClause = `FOREIGN KEY (${cols.trim()}) REFERENCES "${targetTable}" (${targetCols.trim()})`;
    if (onDelete) {
      fkClause += ` ON DELETE ${onDelete.trim()}`;
    }
    if (onUpdate) {
      fkClause += ` ON UPDATE ${onUpdate.trim()}`;
    }
    fksByTable.get(table).push(fkClause);
  }

  // Remove ALTER TABLE foreign key statements
  let resultSql = sql.replace(alterFkRegex, '');

  // Inject inlined foreign keys into matching CREATE TABLE blocks
  for (const [table, fks] of fksByTable.entries()) {
    const tableRegex = new RegExp(`(CREATE TABLE ["']?${table}["']?\\s*\\([\\s\\S]*?)(\\n\\);)`, 'i');
    resultSql = resultSql.replace(tableRegex, (_fullMatch, prefix, suffix) => {
      const fkString = fks.map(fk => `  ${fk}`).join(',\n');
      return `${prefix},\n${fkString}${suffix}`;
    });
  }

  return resultSql;
}

/**
 * 5. Formats the script with generator header comments, SQLite PRAGMAs,
 * collapsed whitespaces, and optional schema_migrations version record.
 *
 * @param {string} sql
 * @param {object} [options]
 * @param {string} [options.sourcePath='schema.dbml']
 * @param {string} [options.migrationName='0001_initial_schema']
 * @param {number} [options.schemaVersion=1]
 * @returns {string}
 */
export function formatSqliteScript(sql, options = {}) {
  const sourcePath = options.sourcePath || 'schema.dbml';
  const migrationName = options.migrationName || '0001_initial_schema';
  const schemaVersion = options.schemaVersion || 1;

  // Collapse consecutive empty lines
  const cleanedSql = sql.replace(/\n{3,}/g, '\n\n').trim();

  let header = `-- ============================================================================\n` +
    `-- Code automatically generated from ${sourcePath}\n` +
    `-- DO NOT EDIT MANUALLY.\n` +
    `-- ============================================================================\n\n` +
    `PRAGMA journal_mode = WAL;\nPRAGMA foreign_keys = ON;\n\n` +
    cleanedSql + '\n';

  if (options.metadataTable) {
    header += `\nINSERT OR IGNORE INTO ${options.metadataTable} (key, value) VALUES ('schema_version', '${schemaVersion}');\n`;
  } else if (options.migrationName || options.schemaVersion) {
    header += `\nINSERT OR IGNORE INTO "schema_migrations" ("version", "name") VALUES (${schemaVersion}, '${migrationName}');\n`;
  }

  return header;
}

/**
 * Executes the complete SQLite normalization pipeline on raw PostgreSQL DDL.
 *
 * @param {string} rawSql - PostgreSQL DDL from exporter
 * @param {object} [options]
 * @param {string} [options.sourcePath='schema.dbml']
 * @param {string} [options.migrationName]
 * @param {number} [options.schemaVersion]
 * @returns {string} Fully normalized SQLite migration script
 */
export function normalizePostgresSqlToSqlite(rawSql, options = {}) {
  let sql = rawSql;

  sql = inlineForeignKeys(sql);
  sql = normalizeAutoIncrement(sql);
  sql = inlineColumnDirectives(sql);
  sql = stripPostgresComments(sql);
  sql = normalizeBooleans(sql);
  sql = formatSqliteScript(sql, options);

  return sql;
}
